/**
 * The panel's copy, in the two languages dsh itself ships.
 *
 * Chinese is the primary UI language (`src/shared/vocabulary.ts` says so for
 * the host's own labels too), so the `zh` side is what the panel said before it
 * had a language at all, and the `en` side is what a reader who switched dsh to
 * English gets. Both sides carry **the same keys** — `test/i18n.test.ts` fails
 * if they drift apart, and if a key is ever missing the lookup falls back to
 * the key itself rather than to a blank line.
 *
 * Placeholders are `{name}` and are filled by `t()`; keep the braces in both
 * languages even when the surrounding word order changes.
 *
 * **What this file does not cover**: the strings the *host* half sends over the
 * wire (probe verdicts, sync errors) and the labels the model sees in tool
 * output. Those travel through `src/shared/**`, are the same in both halves, and
 * need a code-based contract before they can follow a reader's language — see
 * `docs/help/panel-i18n.md`.
 */

